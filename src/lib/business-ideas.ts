/**
 * Convert an `incomePotential` string like "$10k–$25k / mo" into an annual range.
 * Handles /mo, /season, /yr, per-location suffixes, and qualifiers in parens.
 */
export function toAnnualRange(incomePotential: string): string {
  if (!incomePotential) return "";
  // Extract qualifier in parens e.g. "(seasonal)", "(after 6 mo)"
  const qualifierMatch = incomePotential.match(/\(([^)]+)\)/);
  const qualifier = qualifierMatch ? ` (${qualifierMatch[1]})` : "";

  // Extract numeric range
  const nums = Array.from(incomePotential.matchAll(/\$?(\d+(?:\.\d+)?)(k|K|m|M)?/g));
  if (nums.length === 0) return incomePotential;
  const toNumber = (m: RegExpMatchArray) => {
    const n = parseFloat(m[1]);
    const suffix = (m[2] || "").toLowerCase();
    if (suffix === "k") return n * 1_000;
    if (suffix === "m") return n * 1_000_000;
    return n;
  };
  const low = toNumber(nums[0]);
  const high = nums.length > 1 ? toNumber(nums[1]) : low;

  const per = incomePotential.toLowerCase();
  let multiplier = 12;
  if (per.includes("/ yr") || per.includes("/yr") || per.includes("/ year")) multiplier = 1;
  else if (per.includes("season")) multiplier = 1; // seasonal totals are already the season
  else if (per.includes("/ mo") || per.includes("/mo")) multiplier = 12;

  const fmt = (v: number) => {
    if (v >= 1_000_000) return `$${(v / 1_000_000).toFixed(v % 1_000_000 === 0 ? 0 : 1)}M`;
    if (v >= 1_000) return `$${Math.round(v / 1_000)}k`;
    return `$${Math.round(v)}`;
  };

  const annualLow = low * multiplier;
  const annualHigh = high * multiplier;
  const perLocation = per.includes("per location") ? " per location" : "";
  const range = annualLow === annualHigh ? fmt(annualLow) : `${fmt(annualLow)}–${fmt(annualHigh)}`;
  return `${range} / yr${perLocation}${qualifier}`;
}

